from typing import Protocol

class Repository(Protocol):
    def load(self) -> dict | None: ...
    def save(self, data: dict) -> None: ...
    def audit(self, action: str, detail: dict) -> None: ...
    def history(self, *, limit: int | None = 300) -> list[dict]: ...
    def commit(self, data: dict, action: str, detail: dict) -> None: ...
    def commit_many(self, data: dict, entries: list[tuple[str, dict]]) -> None: ...
